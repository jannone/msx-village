import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { root, ensureDependency } from '../../scripts/dependencies.mjs';
const vendor = ensureDependency('MSXgl');
const cwd = resolve(root,'msx'); mkdirSync(resolve(cwd,'out'),{recursive:true});
execFileSync('c++',['-std=c++17','-o','out/MSXhex',`-I${vendor}/tools/MSXtk/src`,`${vendor}/tools/MSXtk/src/MSXhex.cpp`],{cwd,stdio:'inherit'});
execFileSync(process.execPath,[`${vendor}/engine/script/js/build.js`],{cwd,stdio:'inherit'});
const rom = readFileSync(resolve(cwd,'out/village.rom'));
if (rom.length !== 1048576 || rom[0] !== 65 || rom[1] !== 66) throw new Error('Invalid compiled ASCII8 template');
const map = readFileSync(resolve(cwd,'out/village.map'),'utf8');
const data = /^_DATA\s+([A-Fa-f0-9]+)\s+([A-Fa-f0-9]+)/m.exec(map);
if (!data || parseInt(data[1],16)+parseInt(data[2],16)>0xd000) throw new Error('Ordinary RAM overlaps owner buffer');
writeFileSync(resolve(root,'webapp/worker/rom-template.ts'),`// Generated by msx/tools/build.mjs. Rebuild after changing the MSX game.\nexport const CORE_ROM = '${rom.subarray(0,24576).toString('base64')}';\n`);
const { assembleSnapshot } = await import('../../webapp/shared/snapshot.ts');
const code = /^_CODE\s+([A-Fa-f0-9]+)\s+([A-Fa-f0-9]+)/m.exec(map);
if (!code || parseInt(code[1],16)+parseInt(code[2],16)>0xa000) throw new Error('Resident code overlaps switched ROM window');
const { initialSettlement } = await import('../../webapp/shared/settlement.ts');
const neighbor = initialSettlement();
neighbor.interiorObjects.push({kind:3,x:16,y:10});
const plots = [{x:0,y:0,revision:0,username:'Demo',content:initialSettlement()},{x:-1,y:0,revision:0,username:'Neighbor',content:neighbor}];
writeFileSync(resolve(cwd,'out/village-demo.rom'),assembleSnapshot(rom.subarray(0,24576),plots,0,0,{x:0,y:0,revision:0}));
writeFileSync(resolve(cwd,'out/village-visitor.rom'),assembleSnapshot(rom.subarray(0,24576),plots,0,0));
